 for s in w:
  headers={c.column:c.value for c in s[1]}
  for row in s.iter_rows(min_row=2):
   for cell in row:
    if not isinstance(cell.value,str) or not str(headers.get(cell.column,'')).startswith('cn_'):continue
    before=cell.value; after=before
    for old,new in REPLACEMENTS:after=after.replace(old,new)
    if after!=before:cell.value=after;edits.append({'sheet':s.title,'cell':cell.coordinate})
 w.save(path);return edits
